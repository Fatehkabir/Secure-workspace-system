package com.examworkspace.screenshare;

import com.examworkspace.db.Database;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.logging.Logger;

/**
 * Persists and retrieves the active screen-share session for a room.
 *
 * <p>The {@code screen_share_sessions} table is created on first use (auto-migration).
 * When the teacher starts sharing, their LAN IP and port are written here.
 * Students poll this table every 2 seconds; when a row appears they connect,
 * and when it is deleted they close their viewer window.
 */
public final class ScreenShareSessionStore {

    private static final Logger LOG = Logger.getLogger(ScreenShareSessionStore.class.getName());

    private ScreenShareSessionStore() {
    }

    // ── Schema ────────────────────────────────────────────────────────────────

    /**
     * Creates the {@code screen_share_sessions} table if it does not exist.
     * Called once from {@link Database#initialize()}.
     */
    public static void ensureTable() {
        String idDef = Database.isPostgres()
                ? "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
                : "BIGINT AUTO_INCREMENT PRIMARY KEY";
        try (Connection c = Database.connect();
             var st = c.createStatement()) {
            st.execute("CREATE TABLE IF NOT EXISTS screen_share_sessions ("
                    + "room_id BIGINT NOT NULL PRIMARY KEY, "
                    + "host_address VARCHAR(255) NOT NULL, "
                    + "port INT NOT NULL, "
                    + "started_at BIGINT NOT NULL)");
        } catch (SQLException e) {
            LOG.warning("[ScreenShareSessionStore] Could not ensure table: " + e.getMessage());
        }
    }

    // ── Teacher writes ────────────────────────────────────────────────────────

    /**
     * Publishes the teacher's screen-share session so students can find and connect.
     *
     * @param roomId      the room this share belongs to
     * @param hostAddress teacher's LAN IP address (e.g. "192.168.1.5")
     * @param port        TCP port the {@link ScreenShareServer} is listening on
     */
    public static void publish(long roomId, String hostAddress, int port) throws SQLException {
        String upsert = Database.isPostgres()
                ? "INSERT INTO screen_share_sessions(room_id,host_address,port,started_at) VALUES(?,?,?,?)"
                + " ON CONFLICT(room_id) DO UPDATE SET host_address=EXCLUDED.host_address,"
                + " port=EXCLUDED.port, started_at=EXCLUDED.started_at"
                : "MERGE INTO screen_share_sessions(room_id,host_address,port,started_at)"
                + " KEY(room_id) VALUES(?,?,?,?)";
        try (Connection c = Database.connect();
             PreparedStatement ps = c.prepareStatement(upsert)) {
            ps.setLong(1, roomId);
            ps.setString(2, hostAddress);
            ps.setInt(3, port);
            ps.setLong(4, System.currentTimeMillis());
            ps.executeUpdate();
        }
    }

    /**
     * Removes the screen-share session for the room (teacher stopped sharing).
     */
    public static void remove(long roomId) {
        try (Connection c = Database.connect();
             PreparedStatement ps = c.prepareStatement(
                     "DELETE FROM screen_share_sessions WHERE room_id=?")) {
            ps.setLong(1, roomId);
            ps.executeUpdate();
        } catch (SQLException e) {
            LOG.warning("[ScreenShareSessionStore] Remove error: " + e.getMessage());
        }
    }

    // ── Student reads ─────────────────────────────────────────────────────────

    /**
     * Returns the active share session for the given room, or {@code null} if none.
     */
    public static ScreenShareSession find(long roomId) {
        try (Connection c = Database.connect();
             PreparedStatement ps = c.prepareStatement(
                     "SELECT host_address, port FROM screen_share_sessions WHERE room_id=?")) {
            ps.setLong(1, roomId);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    return new ScreenShareSession(rs.getString(1), rs.getInt(2));
                }
            }
        } catch (SQLException e) {
            LOG.fine("[ScreenShareSessionStore] find: " + e.getMessage());
        }
        return null;
    }
}
